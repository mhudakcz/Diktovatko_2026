let LANG = "cs";
function setLang(lang) { LANG = I18N[lang] ? lang : "cs"; document.documentElement.lang = LANG; }
function t(key, params = {}) {
  let s = I18N[LANG][key] ?? I18N.cs[key] ?? key;
  for (const [k, v] of Object.entries(params)) s = s.replaceAll("{" + k + "}", v);
  return s;
}
function tp(kind, n) {
  const forms = (I18N[LANG].plural || I18N.cs.plural)[kind];
  const cat = new Intl.PluralRules(I18N[LANG].locale).select(n);
  const form = forms[cat] ?? forms.other;
  return form.replace("{n}", Math.round(n).toLocaleString(I18N[LANG].locale));
}
function locale() { return I18N[LANG].locale; }
// Statické texty v HTML: data-i18n (text), data-i18n-html (s formátováním), data-i18n-ph (placeholder), data-i18n-aria (aria-label)
function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll("[data-i18n-html]").forEach((el) => (el.innerHTML = t(el.dataset.i18nHtml)));
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
}
